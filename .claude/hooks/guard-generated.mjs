// PreToolUse guard: refuse hand edits to what the pipeline in `parser/` owns.
//
// Two things go wrong when these files are edited directly. The next run of the
// pipeline overwrites the edit without a trace — and the id tables are worse: an
// entry's *position* is its identity, because other files link to it by index,
// so an edit there does not get undone so much as silently re-point every link
// to whatever moved into that slot.
//
// The edit is refused with exit code 2, which blocks the tool call and shows the
// message below to whoever tried. AOW5_ALLOW_GENERATED_EDIT=1 is the deliberate
// escape hatch — a one-off correction the parser cannot express yet.
//
// stdin is the hook payload: { tool_name, tool_input: { file_path, … }, … }.

import { readFileSync } from 'node:fs';

const GENERATED = [
  /(^|\/)packages\/aow5-shared\/public\/data\//,
  /(^|\/)packages\/aow5-shared\/public\/icons\//,
  /(^|\/)packages\/aow5-shared\/data\/[^/]*-table\.json$/,
];

if (process.env.AOW5_ALLOW_GENERATED_EDIT === '1') process.exit(0);

let payload;
try {
  payload = JSON.parse(readFileSync(0, 'utf8'));
} catch {
  process.exit(0); // not our business; a broken payload must never block work
}

const file = payload?.tool_input?.file_path;
if (typeof file !== 'string') process.exit(0);

const path = file.replaceAll('\\', '/');
if (!GENERATED.some((pattern) => pattern.test(path))) process.exit(0);

process.stderr.write(
  `${file} is generated by the pipeline in parser/ — an edit here is overwritten by the next run, ` +
    `and an id table's order is load-bearing (other files point into it by index).\n\n` +
    `Change the source instead and regenerate:\n` +
    `  cd parser && AOW5_VPK=<path to the workshop pak> node tools/run-all.ts\n\n` +
    `What is written by hand lives in packages/aow5-shared/content/ and in ` +
    `packages/aow5-shared/data/name-overrides.json (see CLAUDE.md). ` +
    `For a deliberate exception, set AOW5_ALLOW_GENERATED_EDIT=1.\n`,
);
process.exit(2);
